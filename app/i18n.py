def t(lang: str, key: str, **kwargs: str) -> str:
    table = MESSAGES.get(lang) or MESSAGES["en"]
    text = table.get(key) or MESSAGES["en"].get(key) or key
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, ValueError):
            return text
    return text


def catalog_label(lang: str, kind: str, code: str, fallback: str) -> str:
    return t(lang, f"{kind}.{code}") if f"{kind}.{code}" in MESSAGES.get(lang, {}) or f"{kind}.{code}" in MESSAGES["en"] else fallback
